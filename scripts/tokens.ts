/**
 * Builds the design tokens for the game from `design/tokens.json`, the design system's source of truth.
 *
 * - `src/app/ui/tokens.ts`: typed constants for Pixi (colours as `{ color, alpha }` fills, sizes in px).
 * - `design/tokens.css`: CSS custom properties for the DOM overlay and `design/reference/` pages.
 *
 * Run with `make tokens`. Both outputs are generated: edit `design/tokens.json`, never them.
 */
import { readFileSync, writeFileSync } from 'node:fs';

interface Token {
    name: string;
    value: string | Record<string, string>;
    usage?: string;
}
interface TypeStyle {
    name: string;
    fontSize: string;
    lineHeight: string;
    fontWeight: number;
    letterSpacing?: string;
}
interface Tokens {
    color: { themes: { id: string }[]; tokens: Token[] };
    type: { families: Record<string, string>; groups: { family: string; styles: TypeStyle[] }[] };
    [family: string]: unknown;
}

const root = new URL('..', import.meta.url);
const SOURCE = new URL('design/tokens.json', root);
const TS_OUT = new URL('src/app/ui/tokens.ts', root);
const CSS_OUT = new URL('design/tokens.css', root);
const HEADER = 'Generated by `make tokens` from design/tokens.json. Do not edit.';

const tokens = JSON.parse(readFileSync(SOURCE, 'utf8')) as Tokens;
const theme = tokens.color.themes[0]?.id ?? 'night';
const colors = new Map(tokens.color.tokens.map((t) => [t.name, t]));

const raw = (t: Token): string => (typeof t.value === 'string' ? t.value : (t.value[theme] ?? ''));

/** Follows `{alias}` references to a literal colour. */
function resolve(name: string, seen = new Set<string>()): string {
    const token = colors.get(name);
    if (!token) throw new Error(`[tokens] unknown colour token "${name}"`);
    if (seen.has(name)) throw new Error(`[tokens] alias cycle at "${name}"`);
    seen.add(name);
    const value = raw(token);
    const alias = /^\{(.+)\}$/.exec(value);
    return alias?.[1] ? resolve(alias[1], seen) : value;
}

/** `#rgb`, `#rrggbb`, `#rrggbbaa` or `rgb()/rgba()` → a Pixi fill. */
function toFill(value: string): { color: number; alpha: number } {
    const hex = /^#([0-9a-f]{3,8})$/i.exec(value)?.[1];
    if (hex) {
        const full = hex.length <= 4 ? [...hex].map((c) => c + c).join('') : hex;
        const alpha = full.length === 8 ? parseInt(full.slice(6), 16) / 255 : 1;
        return { color: parseInt(full.slice(0, 6), 16), alpha: round(alpha) };
    }
    const rgb = /^rgba?\(([^)]+)\)$/.exec(value)?.[1];
    if (rgb) {
        const [r = 0, g = 0, b = 0, a = 1] = rgb.split(',').map((n) => Number(n.trim()));
        return { color: (r << 16) | (g << 8) | b, alpha: round(a) };
    }
    throw new Error(`[tokens] unsupported colour "${value}"`);
}

const round = (n: number): number => Math.round(n * 1000) / 1000;
const px = (value: string): number => {
    const n = parseFloat(value);
    if (Number.isNaN(n)) throw new Error(`[tokens] not a length: "${value}"`);
    return n;
};
const listOf = (family: string): Token[] =>
    ((tokens[family] as { tokens?: Token[] } | undefined)?.tokens ?? []).filter(
        (t) => typeof t.value === 'string',
    );
const hex6 = (n: number): string => `0x${n.toString(16).padStart(6, '0')}`;
const doc = (t: { usage?: string }): string =>
    t.usage ? `    /** ${t.usage.replaceAll('*/', '* /')} */\n` : '';

// ---- src/app/ui/tokens.ts
const colorLines = tokens.color.tokens.map((t) => {
    const { color, alpha } = toFill(resolve(t.name));
    return `${doc(t)}    '${t.name}': { color: ${hex6(color)}, alpha: ${alpha} },`;
});
const pxLines = (family: string): string =>
    listOf(family)
        .map((t) => `${doc(t)}    '${t.name}': ${px(raw(t))},`)
        .join('\n');
const typeLines = tokens.type.groups.flatMap((group) =>
    group.styles.map((s) => {
        const size = px(s.fontSize);
        const spacing = s.letterSpacing?.endsWith('em')
            ? round(parseFloat(s.letterSpacing) * size)
            : s.letterSpacing
              ? px(s.letterSpacing)
              : 0;
        return `    '${s.name}': { fontSize: ${size}, lineHeight: ${px(s.lineHeight)}, fontWeight: ${s.fontWeight}, letterSpacing: ${spacing} },`;
    }),
);

const ts = `// ${HEADER}

/** Colours as Pixi fills: pass to \`graphics.fill(COLOR['bg-900'])\`, or use \`.color\` for a tint. */
export const COLOR = {
${colorLines.join('\n')}
} as const;

/** Spacing steps in px (design units). */
export const SPACE = {
${pxLines('spacing')}
} as const;

/** Corner radii in px. \`radius-pill\`: clamp to half the shape's short side. */
export const RADIUS = {
${pxLines('radius')}
} as const;

/** Fixed sizes in px. */
export const SIZE = {
${pxLines('size')}
} as const;

/** Type styles in px; \`letterSpacing\` is already converted from em. */
export const TYPE = {
${typeLines.join('\n')}
} as const;

export type ColorToken = keyof typeof COLOR;
export type SpaceToken = keyof typeof SPACE;
export type TypeToken = keyof typeof TYPE;
`;

// ---- design/tokens.css
const cssVars = [
    ...tokens.color.tokens.map((t) => {
        const value = raw(t);
        const alias = /^\{(.+)\}$/.exec(value);
        return `    --${t.name}: ${alias ? `var(--${alias[1]})` : value};`;
    }),
    ...['spacing', 'radius', 'size', 'shadow'].flatMap((f) =>
        listOf(f).map((t) => `    --${t.name}: ${raw(t)};`),
    ),
    ...Object.entries(tokens.type.families).map(([key, stack]) => `    --font-${key}: ${stack};`),
];
const css = `/* ${HEADER} */\n:root {\n${cssVars.join('\n')}\n}\n`;

writeFileSync(TS_OUT, ts);
writeFileSync(CSS_OUT, css);
console.log(
    `[tokens] wrote ${colorLines.length} colours → src/app/ui/tokens.ts, design/tokens.css`,
);
